# 1st Example - Set

skills = {"Python", "Git", "SQL", "AI"}


# 2nd Example - Set

cities = {"Delhi", "Mumbai", "Bangalore", "Hyderabad"}


# 3rd Example - Set

technology = {"Python", "SQL", "Docker", "ML"}


# Display Dictionary

print(student)
print(employee)
print(product)


# Display Set

print(skills)
print(cities)
print(technology)



# Sets
# 1. A set stores unique elements
# 2. Sets are unordered collections
# 3. Sets use curly braces {}
# 4. Sets support mathematical set operations


# Dictionary
# 1. Dictionary stores data in key-value pairs
# 2. Keys must be unique
# 3. Dictionary uses curly braces {}
# 4. Keys are used to access values
# 5. Dictionary maintains insertion order (Python 3.7+)